"""Build a self-contained Kaggle script that runs the benchmark on a GPU.

Two kernels:

* ``validate`` runs ``bench.gpu_validate`` (canonical/naive solutions, card examples,
  facts) and writes ``gpu_validation.json``;
* ``eval`` runs ``bench.harness.execute`` on generated candidates and writes
  ``execution.jsonl``.

    uv run python bench/kaggle/make_kernel.py validate --user <kaggle-username>
    uv run python bench/kaggle/make_kernel.py eval --user <kaggle-username> \\
        --candidates bench/results/eval-v1/generations.jsonl
    uvx --from kaggle kaggle kernels push -p bench/kaggle/build/<kernel>
    uvx --from kaggle kaggle kernels output <user>/mathlib-mcp-<kernel> -p <dir>

The benchmark code and data are embedded as a base64 zip, so the kernel needs no
dataset: it installs the pinned CuPy / nvmath-python versions, unpacks the bundle and
writes its results to /kaggle/working.
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import tomllib
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BUILD = Path(__file__).resolve().parent / "build"

TEMPLATE = '''\
# Auto-generated by bench/kaggle/make_kernel.py from {commit}. Do not edit.
# {purpose}
import base64
import io
import subprocess
import sys
import zipfile

subprocess.run(["nvidia-smi"], check=False)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", {packages}], check=True)

BUNDLE = "{bundle}"
ROOT = "/kaggle/working/mathlib-mcp"
zipfile.ZipFile(io.BytesIO(base64.b64decode(BUNDLE))).extractall(ROOT)
subprocess.run([sys.executable, "-m", {command}], cwd=ROOT, check=False)
'''

KERNELS = {
    "validate": {
        "purpose": "Validates the mathlib-mcp benchmark and curated API knowledge on a GPU.",
        "command": ["bench.gpu_validate", "--out", "/kaggle/working/gpu_validation.json"],
        "slug": "mathlib-mcp-gpu-validation",
        "title": "mathlib-mcp GPU validation",
    },
    "eval": {
        "purpose": "Executes model-generated solutions of the mathlib-mcp benchmark on a GPU.",
        "command": ["bench.harness.execute", "--candidates", "candidates.jsonl",
                    "--out", "/kaggle/working/execution.jsonl"],
        "slug": "mathlib-mcp-eval",
        "title": "mathlib-mcp eval",
    },
}


def bundle(candidates: Path | None) -> str:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted((REPO / "bench").rglob("*.py")):
            parts = path.relative_to(REPO / "bench").parts
            if parts[0] in ("kaggle", "results") or "__pycache__" in parts:
                continue
            archive.write(path, path.relative_to(REPO))
        cards = REPO / "src" / "mathlib_mcp" / "data" / "cards.json"
        archive.write(cards, cards.relative_to(REPO))
        if candidates is not None:
            # only what execution needs: id, task and code
            rows = [json.loads(line) for line in candidates.read_text().splitlines() if line]
            slim = "\n".join(json.dumps({"id": r["id"], "task": r["task"], "code": r["code"]})
                             for r in rows if r.get("code"))
            archive.writestr("candidates.jsonl", slim + "\n")
    return base64.b64encode(buffer.getvalue()).decode()


def packages() -> list[str]:
    config = tomllib.loads((REPO / "curation" / "libraries.toml").read_text())
    versions = {lib["name"]: lib["version"] for lib in config["library"]}
    return [f"cupy-cuda12x[ctk]=={versions['cupy']}",
            f"nvmath-python[cu12]=={versions['nvmath-python']}"]


def commit() -> str:
    head = (REPO / ".git" / "HEAD").read_text().strip()
    if head.startswith("ref: "):
        ref = REPO / ".git" / head[5:]
        return ref.read_text().strip()[:12] if ref.is_file() else "unknown"
    return head[:12]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("kernel", choices=list(KERNELS))
    parser.add_argument("--user", default="INSERT_USERNAME", help="Kaggle username")
    parser.add_argument("--machine", default="NvidiaTeslaT4",
                        choices=["NvidiaTeslaT4", "NvidiaTeslaP100"])
    parser.add_argument("--candidates", type=Path, help="generations.jsonl (eval kernel)")
    args = parser.parse_args()
    if (args.kernel == "eval") != (args.candidates is not None):
        parser.error("--candidates is required for (and only for) the eval kernel")
    spec = KERNELS[args.kernel]
    out = BUILD / args.kernel
    out.mkdir(parents=True, exist_ok=True)
    script = TEMPLATE.format(commit=commit(), purpose=spec["purpose"],
                             bundle=bundle(args.candidates),
                             packages=", ".join(repr(p) for p in packages()),
                             command=", ".join(repr(c) for c in spec["command"]))
    code_file = f"{args.kernel}_kernel.py"
    (out / code_file).write_text(script, encoding="utf-8")
    metadata = {
        "id": f"{args.user}/{spec['slug']}",
        "title": spec["title"],
        "code_file": code_file,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "machine_shape": args.machine,
    }
    (out / "kernel-metadata.json").write_text(json.dumps(metadata, indent=1))
    print(f"wrote {out / code_file} ({len(script) / 1024:.0f} KiB)")


if __name__ == "__main__":
    main()
