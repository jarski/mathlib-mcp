"""Build a self-contained Kaggle script that runs ``bench.gpu_validate`` on a GPU.

    uv run python bench/kaggle/make_kernel.py
    # -> bench/kaggle/build/gpu_validate_kernel.py (+ kernel-metadata.json)

The benchmark code and the card data are embedded as a base64 zip, so the kernel
needs no dataset: it installs the pinned CuPy / nvmath-python versions, unpacks the
bundle and writes ``gpu_validation.json`` to /kaggle/working.
"""

from __future__ import annotations

import base64
import io
import json
import tomllib
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BUILD = Path(__file__).resolve().parent / "build"

TEMPLATE = '''\
# Auto-generated by bench/kaggle/make_kernel.py from {commit}. Do not edit.
# Validates the mathlib-mcp benchmark and curated API knowledge on a real GPU.
import base64
import io
import subprocess
import sys
import zipfile

subprocess.run([sys.executable, "-m", "pip", "install", "-q", {packages}], check=True)

BUNDLE = "{bundle}"
ROOT = "/kaggle/working/mathlib-mcp"
zipfile.ZipFile(io.BytesIO(base64.b64decode(BUNDLE))).extractall(ROOT)
subprocess.run([sys.executable, "-m", "bench.gpu_validate",
                "--out", "/kaggle/working/gpu_validation.json"], cwd=ROOT, check=False)
'''


def bundle() -> str:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted((REPO / "bench").rglob("*.py")):
            if "kaggle" in path.parts or "__pycache__" in path.parts:
                continue
            archive.write(path, path.relative_to(REPO))
        cards = REPO / "src" / "mathlib_mcp" / "data" / "cards.json"
        archive.write(cards, cards.relative_to(REPO))
    return base64.b64encode(buffer.getvalue()).decode()


def packages() -> list[str]:
    config = tomllib.loads((REPO / "curation" / "libraries.toml").read_text())
    versions = {lib["name"]: lib["version"] for lib in config["library"]}
    return [f"cupy-cuda12x[ctk]=={versions['cupy']}",
            f"nvmath-python[cu12]=={versions['nvmath-python']}"]


def commit() -> str:
    head = (REPO / ".git" / "HEAD").read_text().strip()
    if head.startswith("ref: "):
        ref = REPO / ".git" / head[5:]
        return ref.read_text().strip()[:12] if ref.is_file() else "unknown"
    return head[:12]


def main() -> None:
    BUILD.mkdir(parents=True, exist_ok=True)
    script = TEMPLATE.format(commit=commit(), bundle=bundle(),
                             packages=", ".join(repr(p) for p in packages()))
    (BUILD / "gpu_validate_kernel.py").write_text(script, encoding="utf-8")
    metadata = {
        "id": "INSERT_USERNAME/mathlib-mcp-gpu-validation",
        "title": "mathlib-mcp GPU validation",
        "code_file": "gpu_validate_kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
    }
    (BUILD / "kernel-metadata.json").write_text(json.dumps(metadata, indent=1))
    print(f"wrote {BUILD / 'gpu_validate_kernel.py'} ({len(script) / 1024:.0f} KiB)")


if __name__ == "__main__":
    main()
