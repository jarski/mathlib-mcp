"""Build the Agent Skill from the same data the MCP server serves.

    uv run python scripts/build_skill.py              # refresh skills/<name>/ and dist/<name>.zip
    uv run python scripts/build_skill.py --out DIR    # build a copy elsewhere (tests)

The skill folder holds the hand-written parts (SKILL.md, scripts/). This script adds the
generated parts: references/ rendered from cards.json, LICENSE and NOTICE.md. It then
zips the folder for marketplaces that take "a zip with a SKILL.md", such as Agensi.io.
The SKILL.md frontmatter must name the library versions the data was built from, so a
stale skill fails to build instead of shipping old pitfalls under new version numbers.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
import zipfile
from importlib import resources
from pathlib import Path

from mathlib_mcp.cards import ApiCard, load_cards, load_symbols

ROOT = Path(__file__).resolve().parents[1]
NAME = "cupy-nvmath-gpu-math"
SRC = ROOT / "skills" / NAME
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")

LICENSES = {
    "cupy": ("MIT License", "Copyright (c) 2015 Preferred Networks, Inc.",
             "https://github.com/cupy/cupy/blob/main/LICENSE"),
    "nvmath-python": ("Apache License 2.0", "Copyright (c) NVIDIA CORPORATION & AFFILIATES",
                      "https://github.com/NVIDIA/nvmath-python/blob/main/LICENSE"),
}


def frontmatter(text: str) -> dict[str, str]:
    """The SKILL.md header as a flat dict; nested keys become ``metadata.key``."""
    if not text.startswith("---\n"):
        sys.exit("SKILL.md must start with a '---' frontmatter block")
    header = text[4:text.index("\n---\n", 4)]
    fields: dict[str, str] = {}
    parent = None
    for line in header.splitlines():
        if not line.strip():
            continue
        key, _, value = line.partition(":")
        if line.startswith("  "):
            fields[f"{parent}.{key.strip()}"] = value.strip().strip('"')
        else:
            parent = key.strip()
            fields[parent] = value.strip().strip('"')
    return fields


def check_frontmatter(fields: dict[str, str], libraries: dict) -> None:
    name, description = fields.get("name", ""), fields.get("description", "")
    if name != NAME or not NAME_RE.match(name) or len(name) > 64:
        sys.exit(f"SKILL.md name must be {NAME!r} (lowercase, hyphens), got {name!r}")
    if not 1 <= len(description) <= 1024:
        sys.exit(f"SKILL.md description must be 1-1024 characters, got {len(description)}")
    for library, info in libraries.items():
        declared = fields.get(f"metadata.{library}")
        if declared != info["version"]:
            sys.exit(f"SKILL.md says {library} {declared!r} but the data was built from "
                     f"{info['version']}; update the frontmatter and the text")


def file_for(library: str) -> str:
    return library.replace("-python", "") + ".md"


def contents(cards: list[ApiCard]) -> list[str]:
    curated = [c for c in cards if c.curated]
    plain = [c for c in cards if not c.curated]
    lines = ["## Contents", "",
             f"{len(curated)} curated cards (pitfalls and a GPU-verified example), then "
             f"{len(plain)} cards extracted from the sources.", ""]
    lines += [f"- `{c.id}` ★ {c.summary}" for c in curated]
    lines += [f"- `{c.id}`: {c.summary}" for c in plain]
    return lines + [""]


def render_library(library: str, version: str, cards: list[ApiCard]) -> str:
    lines = [f"# {library} {version}: API cards", "",
             "Generated by [mathlib-mcp](https://github.com/jarski/mathlib-mcp) from the "
             f"{library} sources. Search for ``### `dotted.name` `` to jump to a card. "
             "★ marks curated cards.", ""]
    lines += contents(cards)
    lines += ["## Cards", ""]
    for card in cards:
        lines += [card.to_markdown(full=True), "---", ""]
    return "\n".join(lines)


def render_pitfalls(by_library: dict[str, list[ApiCard]]) -> str:
    lines = ["# Pitfalls", "",
             "Mistakes that look right and fail on the GPU, collected from the curated "
             "cards. Each item names the function it belongs to; the full card has the "
             "signature and a verified example.", ""]
    for library, cards in by_library.items():
        lines += [f"## {library}", ""]
        for card in cards:
            if not card.pitfalls:
                continue
            lines.append(f"### `{card.id}`")
            if card.import_hint:
                lines.append(f"- Import: `{card.import_hint}` (`import "
                             f"{card.import_hint.split()[1].split('.')[0]}` alone is not "
                             "enough).")
            lines += [f"- {p}" for p in card.pitfalls]
            lines.append("")
    return "\n".join(lines)


def render_examples(by_library: dict[str, list[ApiCard]]) -> str:
    lines = ["# Verified examples", "",
             "Complete, runnable examples from the curated cards. Each one was run on the "
             "GPU named in its heading; the asserts passed there.", ""]
    for library, cards in by_library.items():
        lines += [f"## {library}", ""]
        for card in cards:
            if not card.example:
                continue
            label = (f"verified on {card.example_verified_on}" if card.example_verified_on
                     else "curated, not yet verified on a GPU")
            lines += [f"### `{card.id}` ({label})", "",
                      f"```python\n{card.example.strip()}\n```", ""]
    return "\n".join(lines)


def render_notice(libraries: dict) -> str:
    lines = ["# Notices", "",
             "The skill's own text and scripts are MIT licensed (see LICENSE). The "
             "reference files contain signatures, docstrings and examples extracted from "
             "the following libraries, under their licenses:", ""]
    for library, info in libraries.items():
        title, holder, url = LICENSES[library]
        lines.append(f"- **{library} {info['version']}**: {title}. {holder}. {url}")
    lines += ["", "Pitfalls, curated examples and the checker are original work of "
                  "mathlib-mcp (https://github.com/jarski/mathlib-mcp)."]
    return "\n".join(lines) + "\n"


def build(out: Path, zip_path: Path) -> None:
    if out.resolve() != SRC.resolve():
        out.mkdir(parents=True, exist_ok=True)
        shutil.copy(SRC / "SKILL.md", out / "SKILL.md")
        shutil.copytree(SRC / "scripts", out / "scripts", dirs_exist_ok=True)
    libraries = load_symbols()["libraries"]
    check_frontmatter(frontmatter((out / "SKILL.md").read_text(encoding="utf-8")), libraries)

    cards = sorted(load_cards().values(), key=lambda c: c.id)
    by_library = {library: [c for c in cards if c.library == library] for library in libraries}
    refs = out / "references"
    shutil.rmtree(refs, ignore_errors=True)
    refs.mkdir()
    data = resources.files("mathlib_mcp").joinpath("data")
    (refs / "index.md").write_text(data.joinpath("llms.txt").read_text("utf-8"), "utf-8")
    for library, info in libraries.items():
        (refs / file_for(library)).write_text(
            render_library(library, info["version"], by_library[library]), "utf-8")
    (refs / "pitfalls.md").write_text(render_pitfalls(by_library), "utf-8")
    (refs / "examples.md").write_text(render_examples(by_library), "utf-8")
    shutil.copy(ROOT / "LICENSE", out / "LICENSE")
    (out / "NOTICE.md").write_text(render_notice(libraries), "utf-8")

    files = [p for p in sorted(out.rglob("*")) if p.is_file() and "__pycache__" not in p.parts]
    for path in files:
        print(f"  {path.relative_to(out)}: {path.stat().st_size / 1024:.0f} KiB")
    # Two layouts: the skill folder inside the archive (what .skill packages use), and
    # a flat one with SKILL.md at the root, for uploads that expect that.
    flat_path = zip_path.with_name(f"{zip_path.stem}-flat{zip_path.suffix}")
    zip_path.parent.mkdir(parents=True, exist_ok=True)
    for target, prefix in ((zip_path, Path(NAME)), (flat_path, Path())):
        target.unlink(missing_ok=True)
        with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
            for path in files:
                archive.write(path, prefix / path.relative_to(out))
        print(f"wrote {target} ({target.stat().st_size / 1024:.0f} KiB)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=SRC, help="skill folder to build into")
    parser.add_argument("--zip", type=Path, default=ROOT / "dist" / f"{NAME}.zip")
    args = parser.parse_args()
    build(args.out, args.zip)


if __name__ == "__main__":
    main()
